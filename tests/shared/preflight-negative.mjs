import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { database } from "./helpers.mjs";
const db = database();
const args = ["scripts/preflight.mjs", "--local", "--state", ".wrangler/test-state", "--cycle"];
assert.throws(() => execFileSync(process.execPath, [...args, "wrong-cycle"], { stdio: "pipe" }));
assert.equal(db.prepare("SELECT count(*) n FROM sqlite_schema WHERE name='activity_hourly'").get().n, 0);
const before = JSON.stringify(db.prepare("SELECT * FROM d1_migrations").all());
const result = JSON.parse(execFileSync(process.execPath, [...args, "prueba-compartida"], { encoding: "utf8", stdio: "pipe" }));
assert.equal(result.ready, true); assert.equal(result.telemetryRequired, false);
assert.equal(JSON.stringify(db.prepare("SELECT * FROM d1_migrations").all()), before);
db.close();
console.log("PASS preflight rejects wrong cycle and accepts operational schema 0007 without telemetry or writes");
