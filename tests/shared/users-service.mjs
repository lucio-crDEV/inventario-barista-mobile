  countedItem=(await person.boot()).items.find(i=>i.locationId==="servicio:barra" && !db.prepare("SELECT 1 FROM counts WHERE cycle_id='prueba-compartida' AND item_id=? AND location_id=?").get(i.id,i.locationId));
