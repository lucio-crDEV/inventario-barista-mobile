const db = database(); db.exec("DELETE FROM attempts");
const checks = [], admin = new Client(), lead = new Client(), secondLead = new Client(), kitchen = new Client();
await admin.login("admin-prueba"); await lead.login("jefa-servicio"); await secondLead.login("jefa-servicio-2"); await kitchen.login("cocina");
