const account = async (client,id) => (await client.request("/api/admin/users")).data.users.find(u => u.id === id);
const update = async (client,id,patch) => {
  const u = await account(client,id); assert.ok(u);
  return client.request("/api/admin/users/"+id, { expectedRevision:u.revision, grants:u.grants, ...(!u.limited ? { username:u.username,role:u.role,active:u.active } : {}), ...patch });
};
const remove = async (client,id,extra={}) => {
  const u=await account(client,id); assert.ok(u);
  return client.request(`/api/admin/users/${id}/delete`, { expectedRevision:u.revision,confirm:true,...extra });
};
