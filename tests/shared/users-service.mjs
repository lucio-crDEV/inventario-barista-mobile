await test("Eliminación irreversible con confirmación/revisión: sesiones fuera, datos/auditoría intactos",async()=>{
  let target=await account(lead,pureId);
  const before=db.prepare("SELECT count(*) n FROM admin_audit WHERE action='delete-user'").get().n;
  assert.equal((await lead.request(`/api/admin/users/${pureId}/delete`,{expectedRevision:target.revision})).status,400);
  assert.equal((await lead.request(`/api/admin/users/${pureId}/delete`,{confirm:true,expectedRevision:target.revision-1})).status,409);
  assert.equal(db.prepare("SELECT count(*) n FROM admin_audit WHERE action='delete-user'").get().n,before);
  assert.equal((await remove(secondLead,pureId)).status,200);
  assert.equal((await person.request("/api/me")).status,401);
  assert.equal(await account(admin,pureId),undefined);
  assert.equal((await person.request("/api/login",{username:pureName,password:"Servicio-08"})).status,401);
  assert.equal((await admin.request(urlFor("/api/record",countedItem))).data.record.quantity,4);
  assert.equal((await admin.request(urlFor("/api/record",countedItem))).data.record.authorId,pureId);
  assert.throws(()=>db.prepare("UPDATE users SET active=1,deleted_at=NULL WHERE id=?").run(pureId),/DELETED_USER/);
  const recreated=await lead.request("/api/admin/users",{username:pureName,name:"Persona distinta",role:"worker",password});
  assert.equal(recreated.status,201); assert.notEqual(recreated.data.id,pureId);
  assert.deepEqual(db.prepare("PRAGMA foreign_key_check").all(),[]);
  checks.push("Eliminar exige confirmación, no restaura cuentas, conserva autoría/conteos y permite nueva identidad con el username libre");
});
await test("Último administrador y cambios concurrentes sin auditoría parcial",async()=>{
  const a=await account(admin,admin.user.id);
  assert.equal((await remove(admin,a.id)).data.code,"LAST_ADMIN");
  assert.equal((await update(admin,a.id,{role:"service_lead"})).data.code,"LAST_ADMIN");
  assert.equal((await update(admin,a.id,{active:false})).data.code,"LAST_ADMIN");
  const mixed=await account(admin,mixedId), payload={expectedRevision:mixed.revision,username:mixed.username,role:mixed.role,active:mixed.active,grants:mixed.grants};
  const before=db.prepare("SELECT count(*) n FROM admin_audit WHERE target=? AND action='update-user'").get(mixedId).n;
  const raced=await Promise.all([admin.request(`/api/admin/users/${mixedId}`,payload),admin.request(`/api/admin/users/${mixedId}`,{...payload,active:false})]);
  assert.deepEqual(raced.map(r=>r.status).sort(),[200,409]);
  assert.equal(db.prepare("SELECT count(*) n FROM admin_audit WHERE target=? AND action='update-user'").get(mixedId).n,before+1);
  assert.ok(db.prepare("SELECT detail FROM admin_audit").all().every(r=>!/password_hash|Servicio-08|Solo-pruebas-2026/.test(r.detail)));
  checks.push("Último administrador protegido y dos cambios simultáneos aceptan uno, sin auditoría de éxito parcial");
});
