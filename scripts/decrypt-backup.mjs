import { parseArgs } from 'node:util';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { createDecipheriv } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
import { privateDestination, verifiedBackup } from './operations/storage.mjs';
const {values:v} = parseArgs({options:{file:{type:'string'},directory:{type:'string'}}});
if (!v.file || !v.directory) throw Error('Usa --file RESPALDO.ibk --directory NUEVA_CARPETA. Clave en BACKUP_ENCRYPTION_KEY.');
const key = Buffer.from(process.env.BACKUP_ENCRYPTION_KEY || '', 'base64');
const bytes = readFileSync(v.file);
if (key.length !== 32 || bytes.subarray(0,4).toString() !== 'IBK1' || bytes.length < 33) throw Error('Clave o formato inválido');
const decipher = createDecipheriv('aes-256-gcm',key,bytes.subarray(4,16));
decipher.setAAD(Buffer.from('inventory-backup-v1'));
decipher.setAuthTag(bytes.subarray(-16));
const payload = JSON.parse(gunzipSync(Buffer.concat([decipher.update(bytes.subarray(16,-16)),decipher.final()]),{maxOutputLength:128*1024*1024}).toString('utf8'));
const directory = privateDestination(v.directory,'.backups');
mkdirSync(dirname(directory),{recursive:true,mode:0o700});
mkdirSync(directory,{mode:0o700});
writeFileSync(join(directory,'database.sql'),payload.sql,{flag:'wx',mode:0o600});
writeFileSync(join(directory,'manifest.json'),JSON.stringify(payload.manifest)+'\n',{flag:'wx',mode:0o600});
verifiedBackup(directory);
console.log('Respaldo descifrado y checksum verificado. Usa restore:local para ensayar en una base nueva.');
